import * as XLSX from 'xlsx'
import type { Participant, Project, Training } from '../types'
import {
  fileTimestamp,
  formatDate,
  formatDateTime,
  formatNumber,
} from './formatters'

const AGENCY = 'DEPARTMENT OF INFORMATION AND COMMUNICATIONS TECHNOLOGY'
const OFFICE =
  'ABRA PROVINCIAL OFFICE  |  Cordillera Administrative Region  |  Bangued, Abra'
const APP_NAME = 'DICT Abra Integrated Project Monitoring & Training System'

interface SheetOptions {
  sheetName: string
  title: string
  summary: string
  headers: string[]
  rows: Array<Array<string | number>>
  columnWidths: number[]
  numberColumns?: number[]
}

function appendReportSheet(
  workbook: XLSX.WorkBook,
  options: SheetOptions,
): void {
  const generatedAt = new Date()
  const headerRow = 7
  const lastColumn = options.headers.length - 1

  const data: Array<Array<string | number>> = [
    ['REPUBLIC OF THE PHILIPPINES'],
    [AGENCY],
    [OFFICE],
    [options.title.toUpperCase()],
    [`Date Generated: ${formatDateTime(generatedAt.toISOString())}`],
    [options.summary],
    [],
    options.headers,
    ...options.rows,
  ]

  const worksheet = XLSX.utils.aoa_to_sheet(data)

  worksheet['!merges'] = [0, 1, 2, 3, 4, 5].map((row) => ({
    s: { r: row, c: 0 },
    e: { r: row, c: lastColumn },
  }))
  worksheet['!cols'] = options.columnWidths.map((width) => ({ wch: width }))
  worksheet['!rows'] = [
    { hpt: 14 },
    { hpt: 22 },
    { hpt: 16 },
    { hpt: 24 },
    { hpt: 16 },
    { hpt: 26 },
    { hpt: 8 },
  ]
  worksheet['!autofilter'] = {
    ref: XLSX.utils.encode_range({
      s: { r: headerRow, c: 0 },
      e: { r: headerRow + options.rows.length, c: lastColumn },
    }),
  }

  options.numberColumns?.forEach((column) => {
    for (let row = headerRow + 1; row <= headerRow + options.rows.length; row += 1) {
      const address = XLSX.utils.encode_cell({ r: row, c: column })
      const cell = worksheet[address]
      if (cell && cell.t === 'n') {
        cell.z = '#,##0'
      }
    }
  })

  XLSX.utils.book_append_sheet(workbook, worksheet, options.sheetName)
}

function createWorkbook(): XLSX.WorkBook {
  const workbook = XLSX.utils.book_new()
  workbook.Props = {
    Title: 'DICT Abra Report',
    Subject: 'Official offline-generated report',
    Author: 'DICT Abra',
    Company: 'Department of Information and Communications Technology',
    Comments: `Generated by ${APP_NAME}`,
    CreatedDate: new Date(),
  }
  return workbook
}

function writeWorkbook(workbook: XLSX.WorkBook, fileName: string): void {
  XLSX.writeFile(workbook, fileName, {
    compression: true,
    bookSST: true,
  })
}

function countAttendance(participants: Participant[]) {
  return {
    male: participants.filter((participant) => participant.gender === 'Male')
      .length,
    female: participants.filter(
      (participant) => participant.gender === 'Female',
    ).length,
    certified: participants.filter(
      (participant) => participant.attendanceStatus === 'Completed / Certified',
    ).length,
  }
}

function sortParticipants(
  participants: Participant[],
  trainingById: Map<number, Training>,
): Participant[] {
  return [...participants].sort((a, b) => {
    const trainingA = trainingById.get(a.trainingId)?.date ?? ''
    const trainingB = trainingById.get(b.trainingId)?.date ?? ''
    return (
      trainingB.localeCompare(trainingA) || a.fullName.localeCompare(b.fullName)
    )
  })
}

export function exportProjectsExcel(projects: Project[]): void {
  const workbook = createWorkbook()
  const sorted = [...projects].sort((a, b) =>
    a.targetCompletionDate.localeCompare(b.targetCompletionDate),
  )
  const totalBudget = projects.reduce((sum, project) => sum + project.budget, 0)
  const active = projects.filter(
    (project) => project.status === 'In Progress',
  ).length
  const completed = projects.filter(
    (project) => project.status === 'Completed',
  ).length

  appendReportSheet(workbook, {
    sheetName: 'Project Register',
    title: 'Project Monitoring Register',
    summary: `Total Projects: ${projects.length}   |   Active: ${active}   |   Completed: ${completed}   |   Total Allocation: PHP ${formatNumber(totalBudget)}`,
    headers: [
      '#',
      'Project Name',
      'Municipality',
      'Category',
      'Status',
      'Progress (%)',
      'Budget (PHP)',
      'Target Start',
      'Target Completion',
      'Project Leader / Focal Person',
      'Remarks / Issues / Blockers',
      'Last Updated',
    ],
    rows: sorted.map((project, index) => [
      index + 1,
      project.name,
      project.municipality,
      project.category,
      project.status,
      project.progress,
      project.budget,
      formatDate(project.targetStartDate),
      formatDate(project.targetCompletionDate),
      project.leader,
      project.remarks || '',
      formatDateTime(project.updatedAt),
    ]),
    columnWidths: [5, 40, 16, 33, 14, 11, 17, 15, 17, 30, 52, 19],
    numberColumns: [5, 6],
  })

  writeWorkbook(
    workbook,
    `DICT-Abra-Project-Register-${fileTimestamp()}.xlsx`,
  )
}

export function exportTrainingMasterlistExcel(
  trainings: Training[],
  participants: Participant[],
): void {
  const workbook = createWorkbook()
  const sorted = [...trainings].sort((a, b) => b.date.localeCompare(a.date))
  const counts = countAttendance(participants)
  const completed = trainings.filter(
    (training) => training.status === 'Completed',
  ).length

  appendReportSheet(workbook, {
    sheetName: 'Training Masterlist',
    title: 'Training Masterlist',
    summary: `Total Sessions: ${trainings.length}   |   Completed: ${completed}   |   Registered Trainees: ${participants.length}   |   GAD Split: ${counts.male} Male / ${counts.female} Female`,
    headers: [
      '#',
      'Course / Program Title',
      'Date',
      'Duration (Hours)',
      'Venue / LGU',
      'Trainer / Speaker',
      'Status',
      'Registered Trainees',
      'Male',
      'Female',
      'Completed / Certified',
    ],
    rows: sorted.map((training, index) => {
      const roster = participants.filter(
        (participant) => participant.trainingId === training.id,
      )
      const rosterCounts = countAttendance(roster)
      return [
        index + 1,
        training.title,
        formatDate(training.date),
        training.durationHours,
        training.venue,
        training.trainer,
        training.status,
        roster.length,
        rosterCounts.male,
        rosterCounts.female,
        rosterCounts.certified,
      ]
    }),
    columnWidths: [5, 47, 15, 12, 34, 29, 14, 14, 8, 8, 15],
    numberColumns: [3, 7, 8, 9, 10],
  })

  const trainingById = new Map(trainings.map((training) => [training.id, training]))
  appendReportSheet(workbook, {
    sheetName: 'Trainee Attendance',
    title: 'Trainee Attendance Masterlist',
    summary: `All trainee records by training session   |   Total: ${participants.length}   |   Male: ${counts.male}   |   Female: ${counts.female}   |   Completed / Certified: ${counts.certified}`,
    headers: [
      '#',
      'Training Session',
      'Schedule',
      'Trainee Name',
      'Gender',
      'Sector',
      'Email Address',
      'Contact Number',
      'Attendance Status',
      'Date Registered',
    ],
    rows: sortParticipants(participants, trainingById).map(
      (participant, index) => {
        const training = trainingById.get(participant.trainingId)
        return [
          index + 1,
          training?.title ?? 'Unlinked training',
          training ? formatDate(training.date) : '',
          participant.fullName,
          participant.gender,
          participant.sector,
          participant.email,
          participant.contactNumber,
          participant.attendanceStatus,
          formatDate(participant.createdAt),
        ]
      },
    ),
    columnWidths: [5, 45, 15, 28, 9, 18, 32, 18, 22, 15],
  })

  writeWorkbook(
    workbook,
    `DICT-Abra-Training-Masterlist-${fileTimestamp()}.xlsx`,
  )
}

export function exportAttendanceExcel(
  trainings: Training[],
  participants: Participant[],
  scope: Training | null,
): void {
  const workbook = createWorkbook()
  const counts = countAttendance(participants)
  const trainingById = new Map(trainings.map((training) => [training.id, training]))
  const title = scope
    ? 'Trainee Attendance & Certification Report'
    : 'Consolidated Trainee Attendance Report'
  const scheduleContext = scope
    ? `   |   ${formatDate(scope.date)} · ${scope.venue} · ${scope.trainer}`
    : ''

  const headers = scope
    ? [
        '#',
        'Trainee Name',
        'Gender',
        'Sector',
        'Email Address',
        'Contact Number',
        'Attendance Status',
        'Date Registered',
      ]
    : [
        '#',
        'Training Session',
        'Schedule',
        'Trainee Name',
        'Gender',
        'Sector',
        'Email Address',
        'Contact Number',
        'Attendance Status',
        'Date Registered',
      ]

  const rows = sortParticipants(participants, trainingById).map(
    (participant, index) => {
      const training = trainingById.get(participant.trainingId)
      const base: Array<string | number> = [index + 1]
      if (!scope) {
        base.push(
          training?.title ?? 'Unlinked training',
          training ? formatDate(training.date) : '',
        )
      }
      base.push(
        participant.fullName,
        participant.gender,
        participant.sector,
        participant.email,
        participant.contactNumber,
        participant.attendanceStatus,
        formatDate(participant.createdAt),
      )
      return base
    },
  )

  appendReportSheet(workbook, {
    sheetName: scope ? 'Session Attendance' : 'All Attendance',
    title: scope ? `${title} - ${scope.title}` : title,
    summary: `Total Trainees: ${participants.length}   |   Male: ${counts.male}   |   Female: ${counts.female}   |   Completed / Certified: ${counts.certified}${scheduleContext}`,
    headers,
    rows,
    columnWidths: scope
      ? [5, 30, 9, 19, 34, 19, 22, 15]
      : [5, 46, 15, 30, 9, 19, 34, 19, 22, 15],
  })

  writeWorkbook(
    workbook,
    `DICT-Abra-Trainee-Attendance-${scope ? 'Session' : 'Consolidated'}-${fileTimestamp()}.xlsx`,
  )
}
